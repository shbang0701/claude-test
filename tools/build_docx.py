def plain_table(rows, widths):
    return TBL(rows, widths, style=None, borders=NOBORDER, cellmar=CELLMAR)

def figures(items, w=4.9, ratio=0.75, gap=True):
    """그림 여러 장을 나란히. items: [(rid, 캡션), ...]"""
    cells = []
    n = len(items)
    for rid, cap in items:
        cells.append(TC(P(IMG(rid, w, round(w * ratio, 2), "fig"), sp=spacing(after=pt(2))) +
                        P(R(cap, sz=9, color=D.INK_SOFT), sp=spacing(after=0)),
                        w=PCT(100 / n), valign="top"))
    return plain_table([TR(cells)], [100 / n] * n)

def number_row(items):
    """수치 요약 줄: (값, 단위, 이름, 보조) × 3~4."""
    n = len(items); cells = []
    for val, unit, name, sub in items:
        runs = [R(val, sz=20, b=True, color=D.PRIMARY, track=-10)]
        if unit: runs.append(R(" " + unit, sz=10, color=D.INK_SOFT))
        c = (P(R(name, sz=9, color=D.INK_FAINT), sp=spacing(after=pt(1))) +
             P(runs, sp=spacing(after=pt(1))) +
             P(R(sub, sz=8.5, color=D.INK_SOFT), sp=spacing(after=0)))
        cells.append(TC(c, w=PCT(100 / n), valign="top",
                        borders='<w:tcBorders>' + bdr("left", 12, D.PRIMARY_TINT, 0) + '</w:tcBorders>',
                        mar='<w:tcMar><w:left w:w="200" w:type="dxa"/><w:right w:w="120" w:type="dxa"/>'
                            '<w:top w:w="60" w:type="dxa"/><w:bottom w:w="60" w:type="dxa"/></w:tcMar>'))
    return TBL([TR(cells)], [100 / n] * n, style=None, borders=NOBORDER, cellmar=CELLMAR)

def summary_points(items):
    """핵심 요약: 번호 + 한 줄. 표지·개요에 쓴다."""
    rows = []
    for i, (t, d) in enumerate(items, 1):
        rows.append(TR([
            TC(P(R(str(i), sz=13, b=True, color=D.PRIMARY_MID), jc="center",
                 sp=spacing(before=pt(1), after=0)), w=PCT(6), valign="top"),
            TC(P(R(t), style=sid("thead"), sp=spacing(before=0, after=pt(1))) +
               P(R(d, sz=9.5, color=D.INK_SOFT), sp=spacing(after=pt(4))), w=PCT(94), valign="top")]))
    return TBL(rows, [6, 94], style=None, borders=NOBORDER, cellmar=CELLMAR)

