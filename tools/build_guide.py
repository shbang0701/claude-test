def flow(items):
    """가로 흐름 상자 (1 → 2 → 3)."""
    cells = []
    n = len(items)
    for i, (num, t, d) in enumerate(items):
        c = (P([R(num, sz=11, b=True, color=D.PRIMARY_MID)], sp=spacing(after=pt(1))) +
             P([R(t, sz=10.5, b=True, color=D.INK)], sp=spacing(after=pt(1))) +
             P([R(d, sz=9, color=D.INK_SOFT)], sp=spacing(after=0)))
        cells.append(TC(c, w=PCT((100 - 3.2 * (n - 1)) / n), valign="top", fill=D.SURFACE,
                        mar='<w:tcMar><w:left w:w="150" w:type="dxa"/><w:right w:w="120" w:type="dxa"/>'
                            '<w:top w:w="120" w:type="dxa"/><w:bottom w:w="120" w:type="dxa"/></w:tcMar>'))
        if i < n - 1:
            cells.append(TC(P([R("→", sz=12, b=True, color=D.PRIMARY_MID)], jc="center"),
                            w=PCT(3.2), valign="center"))
    widths = []
    for i in range(n):
        widths.append((100 - 3.2 * (n - 1)) / n)
        if i < n - 1: widths.append(3.2)
    return TBL([TR(cells)], widths, style=None, borders=NOBORDER, cellmar=CELLMAR)

